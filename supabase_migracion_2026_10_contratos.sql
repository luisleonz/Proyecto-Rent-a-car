-- ── Clientes: datos que pide el Anexo del contrato ────
alter table clientes
  add column if not exists email          text,
  add column if not exists licencia       text,
  add column if not exists licencia_vence date,
  add column if not exists identificacion text,   -- INE / pasaporte
  add column if not exists direccion      text;

-- ── Vehículos: identificación y fianza sugerida ───────
alter table vehiculos
  add column if not exists vin      text,
  add column if not exists asientos int,
  add column if not exists fianza   numeric(10,2) not null default 0;

-- ── Reservas ──────────────────────────────────────────
alter table reservas
  -- Número de contrato consecutivo (se asigna solo, también a las reservas existentes)
  add column if not exists folio            bigint generated by default as identity,
  add column if not exists hora_entrega     time,
  add column if not exists hora_devolucion  time,
  add column if not exists lugar_entrega    text,
  add column if not exists lugar_devolucion text,
  add column if not exists descuento        numeric(10,2) not null default 0,
  -- 'basica' = Cobertura amplia con deducible · 'cero_deducible' = Protección adicional
  add column if not exists cobertura        text not null default 'basica',
  add column if not exists cobertura_costo  numeric(10,2) not null default 0,
  -- Depósito en garantía (cláusula OCTAVA). Distinto del depósito de apartado.
  add column if not exists fianza           numeric(10,2) not null default 0,
  add column if not exists metodo_fianza    text,
  add column if not exists notas            text;

do $$ begin
  alter table reservas add constraint reservas_cobertura_check
    check (cobertura in ('basica','cero_deducible'));
exception when duplicate_object then null; end $$;

create unique index if not exists reservas_folio_key on reservas(folio);

