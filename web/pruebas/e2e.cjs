/* ── harness ── */
async function escenario(grupo, nombre, fn, opciones = {}) {
  if (process.env.SOLO && !`${grupo} ${nombre}`.toLowerCase().includes(process.env.SOLO.toLowerCase())) return
  const b = new Backend(semilla)
  if (opciones.preparar) opciones.preparar(b)
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: opciones.movil ? { width: 400, height: 860 } : { width: 1280, height: 900 }, timezoneId: 'America/Hermosillo', acceptDownloads: true })
  await ctx.route('http://localhost:1/**', r => b.manejar(r))
  await ctx.route('http://fotos.anterior/**', r => r.fulfill({ status: 200, contentType: 'image/jpeg', path: FOTO }))
  await ctx.route('https://wa.me/**', r => r.fulfill({ status: 200, body: 'wa' }))
  const p = await ctx.newPage()
  const errores = []
  p.on('pageerror', e => errores.push(e.message))
  p.on('dialog', dlg => dlg.accept(opciones.respuesta ?? 'No se presentó'))
  const checks = []
  const ok = (cond, msg) => checks.push({ ok: !!cond, msg })
  try {
    await fn({ p, b, ok, ctx })
  } catch (e) {
    checks.push({ ok: false, msg: 'Excepción: ' + e.message.split('\n')[0] })
  }
  if (errores.length) checks.push({ ok: false, msg: 'Errores en la página: ' + errores.join(' | ') })
  if (checks.some(c => !c.ok) && process.env.SALIDA) await p.screenshot({ path: path.join(process.env.SALIDA, `falla-${nombre.slice(0, 20).replace(/[^a-z]+/gi, "-")}.png`), fullPage: true }).catch(() => {})
  resultados.push({ grupo, nombre, checks })
  const fallas = checks.filter(c => !c.ok)
  console.log(`${fallas.length ? '✗' : '✓'} [${grupo}] ${nombre}${fallas.length ? '\n    ' + fallas.map(f => f.msg).join('\n    ') : ''}`)
  await browser.close()
}

async function entrar(p, email = 'luis@lucianos.mx', pass = 'Admin2026') {
  await p.goto(APP + '/', { waitUntil: 'networkidle' })
  await p.fill('input[type=email]', email); await p.keyboard.press('Enter')
  await p.fill('input[type=password]', pass); await p.keyboard.press('Enter')
  await p.waitForTimeout(1200)
}
